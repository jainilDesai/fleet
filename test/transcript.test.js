import { test } from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import { readTranscript } from '../src/transcript.js';
import { costOf } from '../src/pricing.js';
import { tempHome, user, assistant, toolUse, toolResult, write } from './fixtures.js';

const dir = tempHome();

test('counts each API message once, even when it spans several lines', () => {
  const file = path.join(dir, 'tokens.jsonl');
  const usage = { input_tokens: 1000, output_tokens: 200, cache_read_input_tokens: 5000 };
  write(file, [user('fix the checkout'), assistant('msg_1', [{ type: 'text', text: 'Looking' }], usage), assistant('msg_1', [toolUse('t1', 'Read', { file_path: '/work/shop/a.js' })], usage)]);
  const t = readTranscript(file);
  assert.equal(t.tokens.input, 1000);
  assert.equal(t.tokens.output, 200);
  assert.equal(t.total, 6200);
  assert.equal(t.cost, costOf('claude-sonnet-5', usage));
  assert.equal(t.model, 'claude-sonnet-5');
  assert.equal(t.branch, 'main');
});

test('first and last prompt skip system reminders, meta lines, caveats and slash commands', () => {
  const file = path.join(dir, 'prompts.jsonl');
  write(file, [
    user('<system-reminder>context</system-reminder>'),
    user('Caveat: The messages below were generated by the user'),
    user('meta line', { isMeta: true }),
    user('<system-reminder>x</system-reminder>add a coupon field'),
    assistant('m1', [{ type: 'text', text: 'ok' }]),
    user('<command-name>/review</command-name>'),
  ]);
  const t = readTranscript(file);
  assert.equal(t.firstPrompt, 'add a coupon field');
  assert.equal(t.lastPrompt, 'add a coupon field', '/model, /resume and the like are not what a session is about');
});

test('title prefers the custom title over the AI one; edited files are listed once', () => {
  const file = path.join(dir, 'title.jsonl');
  write(file, [
    user('rename things'),
    JSON.stringify({ type: 'ai-title', aiTitle: 'Rename things' }),
    assistant('m1', [toolUse('e1', 'Edit', { file_path: '/work/shop/a.js' }), toolUse('e2', 'Write', { file_path: '/work/shop/b.js' })]),
    assistant('m2', [toolUse('e3', 'Edit', { file_path: '/work/shop/a.js' }), toolUse('r1', 'Read', { file_path: '/work/shop/c.js' })]),
    JSON.stringify({ type: 'custom-title', customTitle: 'my-rename' }),
  ]);
  const t = readTranscript(file);
  assert.equal(t.title, 'my-rename');
  assert.deepEqual(t.edited, ['/work/shop/a.js', '/work/shop/b.js']);
  assert.equal(t.activity.at(-1).tool, 'Read');
});

test('a background agent is finished by its task notification, not by its launch reply', () => {
  const file = path.join(dir, 'agents.jsonl');
  write(file, [
    user('research this'),
    assistant('m1', [toolUse('bg', 'Agent', { description: 'scan repo' }), toolUse('fg', 'Agent', { description: 'quick look' })]),
    user([toolResult('bg', 'Agent launched successfully in the background'), toolResult('fg', 'done: nothing found')]),
  ]);
  let t = readTranscript(file);
  assert.ok(t.finishedToolUses.has('fg'));
  assert.ok(!t.finishedToolUses.has('bg'));
  fs.appendFileSync(file, user('<task-notification><tool-use-id>bg</tool-use-id><status>completed</status></task-notification>') + '\n');
  t = readTranscript(file);
  assert.ok(t.finishedToolUses.has('bg'));
});

test('reads only appended lines, and waits for a half-written last line', () => {
  const file = path.join(dir, 'incremental.jsonl');
  write(file, [user('one'), assistant('m1', [{ type: 'text', text: 'a' }])]);
  assert.equal(readTranscript(file).tokens.output, 50);
  const next = assistant('m2', [{ type: 'text', text: 'b' }]);
  fs.appendFileSync(file, next.slice(0, 20));
  assert.equal(readTranscript(file).tokens.output, 50);
  fs.appendFileSync(file, next.slice(20) + '\n');
  assert.equal(readTranscript(file).tokens.output, 100);
});

test('flags a long transcript it cannot recognize, but not a short or normal one', () => {
  const odd = path.join(dir, 'odd.jsonl');
  write(odd, Array.from({ length: 25 }, (_, i) => JSON.stringify({ kind: 'turn', n: i })));
  assert.equal(readTranscript(odd).formatOk, false);
  const short = path.join(dir, 'short.jsonl');
  write(short, [JSON.stringify({ kind: 'turn' })]);
  assert.equal(readTranscript(short).formatOk, true);
  assert.equal(readTranscript(path.join(dir, 'tokens.jsonl')).formatOk, true);
});
